"""
Link-State Packet (LSP) and Data Packet Definitions for Link State Routing Simulation.
"""

from dataclasses import dataclass, field
import time
from typing import Dict, List, Optional


@dataclass
class LSP:
    """
    Link-State Packet (LSP).
    Generated by each router to advertise its active neighbors and link costs.
    """
    router_id: str
    sequence_number: int
    neighbors: Dict[str, float]  # neighbor_id -> link cost (weight)
    age: int = 64  # Time to live / age counter in flooding
    timestamp: float = field(default_factory=time.time)

    def is_newer_than(self, other: Optional["LSP"]) -> bool:
        """Check if this LSP has a higher sequence number than an existing LSP."""
        if other is None:
            return True
        return self.sequence_number > other.sequence_number

    def copy(self) -> "LSP":
        """Create a deep copy of this LSP with decremented age."""
        return LSP(
            router_id=self.router_id,
            sequence_number=self.sequence_number,
            neighbors=dict(self.neighbors),
            age=self.age,
            timestamp=self.timestamp,
        )

    def __repr__(self) -> str:
        nbr_str = ", ".join(f"{k}:{v}" for k, v in sorted(self.neighbors.items()))
        return f"LSP(from={self.router_id}, seq={self.sequence_number}, age={self.age}, links=[{nbr_str}])"


@dataclass
class DataPacket:
    """
    Data payload packet routed hop-by-hop across the network.
    """
    src: str
    dst: str
    payload: str
    ttl: int = 30
    path_traversed: List[str] = field(default_factory=list)
    accumulated_cost: float = 0.0
    delivered: bool = False
    error: Optional[str] = None

    def add_hop(self, router_id: str, cost: float = 0.0):
        self.path_traversed.append(router_id)
        self.accumulated_cost += cost
        self.ttl -= 1
